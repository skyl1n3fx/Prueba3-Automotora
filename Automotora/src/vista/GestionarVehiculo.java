    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        try {
            int codigo = Integer.parseInt(txtCodigo.getText());
            AutoDAO dao = new AutoDAO();
            Auto auto = dao.buscar(codigo);

            cboMarca.setSelectedIndex(auto.getMarca().getId());
            cboColor.setSelectedIndex(auto.getColor().getId());
            cboModelo.setSelectedIndex(auto.getModelo().getId());
            txtAnio.setText(auto.getAnio());
            txtKm.setText(auto.getKm());
            txtPrecio.setText("" + auto.getPrecio());
            if (auto.isNuevo()) {
                rbtnSi.setSelected(true);
            } else {
                rbtnNo.setSelected(true);
            }

            habilitarCamposModificar();
        } catch (Exception e) {
            mensaje("¡Ingrese un código válido!");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    public void llenarCboColor() {
        ColorDAO dao = new ColorDAO();
        for (Color x : dao.listar()) {
            cboColor.addItem(x.getDescripcion());
        }
    }

    public void llenarCboModelo() {
        ModeloDAO dao = new ModeloDAO();
        for (Modelo x : dao.listar()) {
            cboModelo.addItem(x.getDescripcion());
        }
    }

    public void llenarCboMarca() {
        MarcaDAO dao = new MarcaDAO();
        for (Marca x : dao.listar()) {
            cboMarca.addItem(x.getDescripcion());
        }
    }

    public void mensaje(String texto) {
        JOptionPane.showMessageDialog(null, texto);
    }

    public void limpiar() {
        if (validarVista()) {
            txtCodigo.setText("");
            cboMarca.setSelectedIndex(0);
            cboColor.setSelectedIndex(0);
            cboModelo.setSelectedIndex(0);
            txtAnio.setText("");
            rbtnSi.setSelected(true);
            txtKm.setText("");
            txtPrecio.setText("");
        } else {
            txtCodigo.setText("");
            cboMarca.setSelectedIndex(0);
            cboColor.setSelectedIndex(0);
            cboModelo.setSelectedIndex(0);
            txtAnio.setText("");
            rbtnSi.setSelected(true);
            txtKm.setText("");
            txtPrecio.setText("");
            deshabilitarCamposModificar();
        }

    }

