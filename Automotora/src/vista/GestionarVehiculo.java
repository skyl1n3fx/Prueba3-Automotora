    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {
            int marcaID = cboMarca.getSelectedIndex();
            int colorID = cboColor.getSelectedIndex();
            int modeloID = cboModelo.getSelectedIndex();
            String anio = txtAnio.getText();
            boolean nuevo = rbtnSi.isSelected();
            String km = txtKm.getText();
            int precio = Integer.parseInt(txtPrecio.getText());

            Marca marca = new Marca(marcaID);
            Modelo modelo = new Modelo(modeloID);
            Color color = new Color(colorID);

            Auto auto = new Auto(precio, anio, km, nuevo, modelo, marca, color);

            AutoDAO dao = new AutoDAO();

            if (dao.agregar(auto)) {
                mensaje("¡Vehículo agregado con éxito!");
                limpiar();
            } else {
                mensaje("¡Vehículo no agregado!");
            }

        } catch (Exception e) {
            mensaje("¡Error, el vehículo no se pudo agregar!");
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

