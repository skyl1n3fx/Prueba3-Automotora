    public void seleccionarVista(int seleccion) {
        if (seleccion == 1) {
            lblGestion.setText("AGREGAR");
        } else if (seleccion == 2) {
            lblGestion.setText("MODIFICAR");
        }
    }

    private boolean validarVista() {
        boolean valida = false;
        if (lblGestion.getText().equals("AGREGAR")) {
            valida = true;
        }
        return valida;
    }


