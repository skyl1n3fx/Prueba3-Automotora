    public void actualizarTabla() {
        borrarDatosTabla();
        List<Auto> listaAutos = new ArrayList<Auto>();
        AutoDAO dao = new AutoDAO();
        listaAutos = dao.listar();
        String[] datos = new String[8];
        String nuevo = "No";
        for (Auto x : listaAutos) {

            if (x.isNuevo()) {
                nuevo = "Sí";
            }
            datos[0] = "" + x.getId();
            datos[1] = x.getMarca().getDescripcion();
            datos[2] = x.getModelo().getDescripcion();
            datos[3] = x.getColor().getDescripcion();
            datos[4] = x.getAnio();
            datos[5] = x.getKm();
            datos[6] = nuevo;
            datos[7] = "$" + x.getPrecio();

            tablaAuto.addRow(datos);

        }

        jTableAuto.setModel(tablaAuto);
    }

    public void borrarDatosTabla() {
        tablaAuto.setRowCount(0);
    }
    
